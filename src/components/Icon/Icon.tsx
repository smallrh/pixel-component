export default function Icon({
  name,
  size = "md",
  color,
  spin = false,
  className,
  style,
}: IconProps) {
  const glyph = GLYPHS[name];
  const w = glyph[0].length;
  const h = glyph.length;

  return (
    <span
      className={clsx("pixel-icon", `pixel-icon--${size}`, spin && "pixel-icon--spin", className)}
      style={style}
      role="img"
      aria-label={name}
    >
      <svg
        viewBox={`0 0 ${w} ${h}`}
        width={size === "sm" ? 12 : size === "lg" ? 24 : 16}
        height={size === "sm" ? 12 : size === "lg" ? 24 : 16}
        shapeRendering="crispEdges"
        fill={color ?? "currentColor"}
      >
        {glyph.flatMap((row, y) =>
          row
            .split("")
            .map((ch, x) => (ch === "#" ? <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} /> : null))
        )}
      </svg>
    </span>
  );
}
